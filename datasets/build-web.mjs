#!/usr/bin/env node
/**
 * datasets/web/: what the browser fetches for the whole-store features, cut
 * into small static files so nothing downloads the whole store.
 *
 *     node datasets/build-web.mjs          # after topic builds and atlas.mjs (seconds)
 *
 * Before (2026-11-17, 70,356 entries) the browser fetched whole-store files:
 * topics/all.json 14 MB (Meanwhile, cross-topic quiz), topics/store-lite.json
 * 18 MB (search), atlas/details.json 60 MB (atlas cards and panel). They grow
 * with the store; a phone cannot load them at 10x. Here each request fetches
 * what it needs, and the bytes per request do not grow with the store.
 *
 *   trows/manifest.json      topics {slug: title, group, chapters} + time buckets
 *   trows/b-NNN.json         topic timeline rows (all.json rows), by anchor year,
 *                            ~TROW_BUCKET rows each: Meanwhile, "In your topics"
 *   trows/t/<slug>.json      one topic's rows: cross quiz Everything, review
 *   trows/t/<slug>.key.json  its essentials + key ideas: cross quiz (a session
 *                            samples topics, so this never loads every topic)
 *   lite/time/manifest.json  time buckets of the whole store (lite rows): date pages
 *   lite/time/t-NNN.json     rows whose years overlap the bucket (a span in every
 *                            bucket it overlaps, if at most SPAN_BUCKETS)
 *   lite/time/long.json      spans over more buckets than that (eras, dynasties)
 *   lite/rows/r-NNN.json     all lite rows, ROWS_PER_BLOCK each, most important first
 *   words/<pp>.json          word index (lib/webindex.mjs), by first two letters
 *   details/l-NNN.json       atlas excerpts/facets by atlas leaf group (cards on
 *                            screen are near each other, so few files per view)
 *   manifest.json            built, counts, N (rows), blocks
 *
 * Inputs (generated by topic.mjs / atlas.mjs, not deployed): topics/all.json,
 * topics/store-lite.json, atlas/details.json, atlas/atlas.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { PATHS, DATASETS_DIR } from './lib/store.mjs';
import { tokens, shardOf, POSTINGS_MAX, ROWS_PER_BLOCK } from './lib/webindex.mjs';
import { anchorYear } from '../project/features/topic/layout.js';

const OUT = path.join(DATASETS_DIR, 'web');
const TROW_BUCKET = 600, LITE_BUCKET = 800, SPAN_BUCKETS = 6, LEAF_PART = 200, LEAF_GROUP_ROWS = 200;
const read = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));
const t0 = Date.now();

// Fresh output: a stale shard from a previous build must not survive.
fs.rmSync(OUT + '.tmp', { recursive: true, force: true });
const W = OUT + '.tmp';
const put = (rel, obj) => { const f = path.join(W, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, JSON.stringify(obj)); };
const pad = (i) => String(i).padStart(3, '0');

/** Cut sorted values into consecutive buckets of about `size`, never splitting equal keys. */
function buckets(sorted, key, size){
  const out = [];
  let i = 0;
  while(i < sorted.length){
    let j = Math.min(sorted.length, i + size);
    while(j < sorted.length && key(sorted[j]) === key(sorted[j - 1])) j++;
    out.push(sorted.slice(i, j));
    i = j;
  }
  return out;
}

// ---------------------------------------------------------------------------
// Topic rows (all.json)
// ---------------------------------------------------------------------------
const A = read(path.join(PATHS.topics, 'all.json'));
const idx = read(path.join(PATHS.topics, 'index.json'));
const live = new Set(idx.topics.filter((t) => !t.absorbedInto).map((t) => t.slug));
const trows = A.items.filter((r) => live.has(r.x));
// Image URLs share a long prefix: "~" stands for it (the browser expands it, as for lite rows).
const shortImg = (u) => String(u).replace(/^https:\/\/upload\.wikimedia\.org\/wikipedia\//, '~');
for(const r of trows){
  if(!r.i) r.a = anchorYear({ type: r.ty, kind: r.k ? 'span' : 'point', start: r.s, end: r.e, dataset: r.d });
  if(r.im) r.im = shortImg(r.im);
}
const clip = (s, n) => (s && s.length > n ? s.slice(0, n).replace(/\s+\S*$/, '') + '…' : s);
const dated = trows.filter((r) => !r.i).sort((a, b) => a.a - b.a);
const tb = buckets(dated, (r) => r.a, TROW_BUCKET);
tb.forEach((rows, i) => put(`trows/b-${pad(i)}.json`, rows));
put('trows/manifest.json', {
  topics: Object.fromEntries(Object.entries(A.topics).filter(([s]) => live.has(s))),
  buckets: tb.map((rows, i) => ({ lo: rows[0].a, hi: rows.at(-1).a, f: `b-${pad(i)}.json`, n: rows.length })),
});
const byTopic = new Map();
for(const r of trows) (byTopic.get(r.x) || byTopic.set(r.x, []).get(r.x)).push(r);
for(const [x, rows] of byTopic){
  put(`trows/t/${x}.json`, rows);
  put(`trows/t/${x}.key.json`, rows.filter((r) => r.key).map((r) => ({ ...r, c: clip(r.c, 200) })));
}

// ---------------------------------------------------------------------------
// Whole store (store-lite.json): time buckets, row blocks, word index
// ---------------------------------------------------------------------------
const L = read(path.join(PATHS.topics, 'store-lite.json')).items;
const NOW = new Date().getFullYear();
const endOf = (r) => (r.o ? NOW : r.e ?? r.s);

// Row numbers: in a topic first, then fame, so a query's best hits share blocks.
const order = [...L].sort((a, b) => (b.x ? 1 : 0) - (a.x ? 1 : 0) || (b.f || 0) - (a.f || 0) || (b.im ? 1 : 0) - (a.im ? 1 : 0));
const rowNo = new Map(order.map((r, i) => [r.id, i]));
for(let i = 0; i * ROWS_PER_BLOCK < order.length; i++) put(`lite/rows/r-${pad(i)}.json`, order.slice(i * ROWS_PER_BLOCK, (i + 1) * ROWS_PER_BLOCK));

// Time buckets on start year; a span also joins every later bucket it reaches.
const datedL = L.filter((r) => r.s != null).sort((a, b) => a.s - b.s);
const lb = buckets(datedL.filter((r) => true), (r) => r.s, LITE_BUCKET).map((rows) => ({ lo: rows[0].s, rows: [...rows] }));
lb.forEach((b, i) => { b.hi = i + 1 < lb.length ? lb[i + 1].lo - 1 : Infinity; });
const long = [];
for(const [bi, b] of lb.entries()){
  for(const r of [...b.rows]){
    const e = endOf(r);
    if(e <= b.hi) continue;
    let last = bi;
    while(last + 1 < lb.length && lb[last + 1].lo <= e) last++;
    if(last - bi + 1 > SPAN_BUCKETS){ long.push(r); b.rows.splice(b.rows.indexOf(r), 1); continue; }
    for(let k = bi + 1; k <= last; k++) lb[k].rows.push(r);
  }
}
lb.forEach((b, i) => put(`lite/time/t-${pad(i)}.json`, b.rows));
put('lite/time/long.json', long);
put('lite/time/manifest.json', { buckets: lb.map((b, i) => ({ lo: b.lo, hi: Number.isFinite(b.hi) ? b.hi : null, f: `t-${pad(i)}.json`, n: b.rows.length })), long: long.length });

// Word index: title x3, description, first sentence; weight boosted by being in
// a topic and by fame, so the truncated postings keep what people look for.
const post = new Map();   // token -> Map(row -> weight)
for(const r of L){
  const row = rowNo.get(r.id);
  const tf = new Map();
  const add = (text, w) => { for(const t of tokens(text)) tf.set(t, (tf.get(t) || 0) + w); };
  add(r.t, 3); add(r.sub, 1); add(r.c, 0.6);
  const boost = 1 + (r.x ? 0.5 : 0) + 0.08 * (r.f || 0);
  const len = tokens(r.t).length;
  for(const [t, f] of tf){
    const w = +((f / (f + 1.2)) * boost * (len <= 3 ? 1.15 : 1)).toFixed(3);
    (post.get(t) || post.set(t, new Map()).get(t)).set(row, w);
  }
}
const shards = new Map();
for(const [t, m] of post){
  const list = [...m].sort((a, b) => b[1] - a[1]).slice(0, POSTINGS_MAX);
  const s = shardOf(t);
  (shards.get(s) || shards.set(s, {}).get(s))[t] = [m.size, ...list];
}
for(const [s, obj] of shards) put(`words/${s}.json`, obj);

// ---------------------------------------------------------------------------
// Atlas details, by leaf group
// ---------------------------------------------------------------------------
const atlas = read(PATHS.atlas);
const details = read(PATHS.details);
const P = atlas.points;
const byLeaf = new Map();
P.id.forEach((id, i) => (byLeaf.get(P.leaf[i]) || byLeaf.set(P.leaf[i], []).get(P.leaf[i])).push(id));
// A leaf's points in atlas order, cut into parts of LEAF_PART (one cluster can
// hold 1,000+); consecutive parts packed into groups of ~LEAF_GROUP_ROWS. The
// browser finds a point's file from its leaf and its rank within the leaf.
const leafGroup = {};
let g = 0, cur = 0;
const files = new Map();
for(const leaf of [...byLeaf.keys()].sort((a, b) => a - b)){
  const ids = byLeaf.get(leaf);
  for(let part = 0; part * LEAF_PART < ids.length; part++){
    const chunk = ids.slice(part * LEAF_PART, (part + 1) * LEAF_PART);
    if(cur && cur + chunk.length > LEAF_GROUP_ROWS){ g++; cur = 0; }
    leafGroup[`${leaf}:${part}`] = g; cur += chunk.length;
    const f = files.get(g) || files.set(g, {}).get(g);
    for(const id of chunk){ const d = details[id]; if(d) f[id] = { excerpt: d.excerpt, facets: d.facets, origin: d.origin }; }
  }
}
for(const [k, f] of files) put(`details/l-${pad(k)}.json`, f);
put('details/leaves.json', { part: LEAF_PART, groups: leafGroup });
// Facets alone (1.5 MB at 70k entries): the cluster quiz decides what to ask from them up front.
put('details/facets.json', Object.fromEntries(Object.entries(details).filter(([, d]) => d.facets && Object.keys(d.facets).length).map(([id, d]) => [id, d.facets])));

// Id aliases (store/id-aliases.json): the browser moves answer records with them.
{
  let map = {};
  try { map = read(path.join(PATHS.store, 'id-aliases.json')); } catch {}
  put('aliases.json', { v: Object.keys(map).length, map });
}

put('manifest.json', { built: new Date().toISOString(), N: order.length, blocks: Math.ceil(order.length / ROWS_PER_BLOCK), rowsPerBlock: ROWS_PER_BLOCK,
  trows: trows.length, liteBuckets: lb.length, words: post.size, detailGroups: files.size });

fs.rmSync(OUT, { recursive: true, force: true });
fs.renameSync(W, OUT);

// Report: file count and the biggest file (nothing a phone fetches should be large).
let n = 0, big = ['', 0], total = 0;
const walk = (d) => { for(const f of fs.readdirSync(d)){ const p = path.join(d, f); const s = fs.statSync(p); if(s.isDirectory()) walk(p); else { n++; total += s.size; if(s.size > big[1]) big = [path.relative(OUT, p), s.size]; } } };
walk(OUT);
console.log(`  web/: ${n} files, ${(total / 1e6).toFixed(0)} MB · biggest ${big[0]} ${(big[1] / 1e3).toFixed(0)} KB · ${tb.length} topic-row buckets, ${lb.length} time buckets (+${long.length} long spans), ${post.size} words, ${files.size} detail groups · ${((Date.now() - t0) / 1000).toFixed(1)} s`);
